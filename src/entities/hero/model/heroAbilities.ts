/**
 * Документация способностей героя для карточки /heroes/$code.
 */
export function getHeroAbilities(code: string, isPlayable: boolean): HeroAbilityDoc {
	const pilot = PILOTS[code];
	if (pilot) {
		return pilot;
	}

	if (!isPlayable) {
		return {
			slots: [],
			summonNote:
				'Появляется на поле как призванное существо. Полный набор слотов у хозяина призыва; у саммона — обычные действия боя.',
		};
	}

	const skill = LITE_SKILL[code];
	const slots: HeroAbilitySlot[] = [
		{
			slot: 1,
			title: 'Основная атака',
			body: 'Стандартное действие хода по правилам стиля атаки класса (ближний / дальний / магия).',
		},
	];
	if (skill) {
		slots.push({
			slot: 2,
			title: skill.title,
			body: skill.body,
		});
	}
	return { slots };
}
